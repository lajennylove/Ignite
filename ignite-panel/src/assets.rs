//! The panel's own built stylesheet and script, as the `ui` asset namespace.
//!
//! They are built from `ui/` (Tailwind and Vite) into `ui/dist/build`, which is
//! committed. A release build compiles the manifest and the files into the crate,
//! so it needs no files on disk and no Node. A debug build reads `ui/dist`, so
//! `npm run dev` in `ui/` takes over with hot reload.

use propel_rocket::{global_assets, register_asset_namespace};
use propel_runtime::AssetSource;

/// The name the panel's views use for its own assets: `@vite('ui::resources/css/app.css')`.
pub(crate) const NAMESPACE: &str = "ui";

/// The Vite entries the panel loads, as names in the `ui` namespace.
pub(crate) const ENTRIES: &[&str] = &["ui::resources/css/app.css", "ui::resources/js/app.js"];

/// The build's manifest, compiled in.
const MANIFEST: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/ui/dist/build/manifest.json"
));

// `FILES`: every built file, generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/panel_files.rs"));

/// The panel's build as an asset source. A release build uses the files compiled into
/// the crate. A debug build reads `ui/dist`, so `npm run dev` in `ui/` takes effect at
/// once. The URL prefix is set when the panel registers the namespace.
fn source() -> AssetSource {
    if cfg!(debug_assertions) {
        AssetSource::directory(concat!(env!("CARGO_MANIFEST_DIR"), "/ui/dist"))
    } else {
        AssetSource::memory(MANIFEST, FILES)
    }
}

/// Registers the panel's build as the `ui` namespace, served under `{mount}/build`. The
/// panel does this itself, so an app adds no line for its styling.
pub(crate) fn register(mount: &str) {
    register_asset_namespace(
        NAMESPACE,
        source(),
        &format!("{}/build", mount.trim_end_matches('/')),
    );
}

/// The tags that load the panel's stylesheet and script, for the 419 page, which is not a view.
pub(crate) fn tags() -> String {
    let entries: Vec<String> = ENTRIES.iter().map(|entry| entry.to_string()).collect();
    global_assets().tags(&entries).unwrap_or_default()
}

/// The bytes of a built file, served under `{mount}/build`. In a debug build the files
/// come from `ui/dist` instead, so `None` is returned for them.
pub(crate) fn file(path: &str) -> Option<Vec<u8>> {
    let name = format!("{NAMESPACE}::{path}");
    if let Some(bytes) = global_assets().file(&name) {
        return Some(bytes.to_vec());
    }
    if cfg!(debug_assertions) {
        let disk =
            std::path::Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/ui/dist/build")).join(path);
        return std::fs::read(disk).ok();
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_manifest_names_both_entries() {
        for entry in ENTRIES {
            let name = entry.strip_prefix("ui::").unwrap();
            assert!(MANIFEST.contains(name), "manifest lacks {name}");
        }
    }
}
